import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const rows = JSON.parse(await fs.readFile('examples/workbook_rows.json', 'utf8'));
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('Survey Data');
sheet.getRange('A1:T31').values = rows;
sheet.showGridLines = false;
sheet.getRange('A1:T31').format.font = {name: 'Arial', size: 10};
sheet.getRange('A1:T1').format = {fill: '#243746', font: {name: 'Arial', color: '#FFFFFF', bold: true}, wrapText: true, rowHeight: 160};
sheet.getRange('A2:T31').format.rowHeight = 60;
sheet.getRange('A1:A31').format.columnWidth = 12;
sheet.getRange('B1:C31').format.columnWidth = 24;
sheet.getRange('D1:D31').format.columnWidth = 14;
sheet.getRange('E1:E31').format.columnWidth = 30;
sheet.getRange('F1:G31').format.columnWidth = 24;
sheet.getRange('H1:R31').format.columnWidth = 30;
sheet.getRange('S1:T31').format.columnWidth = 52;
sheet.getRange('E2:E31').format.wrapText = true;
sheet.getRange('H2:P31').format.wrapText = true;
sheet.getRange('S2:T31').format.wrapText = true;
sheet.getRange('Q2:R31').setNumberFormat('0');
sheet.freezePanes.freezeRows(1);
sheet.freezePanes.freezeColumns(1);
workbook.recalculate();
console.log((await workbook.inspect({kind:'table', range:'Survey Data!A1:T4', tableMaxRows:4, tableMaxCols:20, maxChars:2000})).ndjson);
const preview = await workbook.render({sheetName:'Survey Data',range:'A1:T4',scale:1,format:'png'});
await fs.writeFile('.k3-build/preview.png', new Uint8Array(await preview.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(workbook)).save('examples/synthetic_survey.xlsx');
